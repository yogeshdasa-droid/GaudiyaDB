export const dicts: Record<Lang, Dict> = { es, en };
export type T = Dict;

export function formatDate(d: string | null, lang: Lang): string {
  if (!d) return "";
  const [y, m, day] = d.split("-").map(Number);
  const locale = lang === "es" ? "es-ES" : "en-GB";
  if (day) return new Date(y, m - 1, day).toLocaleDateString(locale, { day: "numeric", month: "short", year: "numeric" });
  if (m) return new Date(y, m - 1, 1).toLocaleDateString(locale, { month: "short", year: "numeric" });
  return String(y);
}

export function timeAgo(epochSecs: number | null, lang: Lang): string {
  if (!epochSecs) return dicts[lang].never;
  const diff = Math.round(epochSecs - Date.now() / 1000);
  const rtf = new Intl.RelativeTimeFormat(lang, { numeric: "auto" });
  const abs = Math.abs(diff);
  if (abs < 60) return rtf.format(diff, "second");
  if (abs < 3600) return rtf.format(Math.round(diff / 60), "minute");
  if (abs < 86400) return rtf.format(Math.round(diff / 3600), "hour");
  return rtf.format(Math.round(diff / 86400), "day");
}
